def overlay_row(question_id: str) -> dict[str, Any]:
    qid = str(question_id)
    decision = DECISIONS.get(qid, "")
    if not decision:
        raise KeyError(f"predecessor {qid} has no tested_decision overlay")
    related = WITHHELD.get(qid)
    if related:
        return {
            "tested_decision": decision,
            "disposition": "withheld",
            "semantic_independence": "WITHHELD_SEMANTIC_DUPLICATE",
            "related_to": related,
            "repair_required": False,
            "repair_summary": f"Withheld as a paraphrase of {related}; same tested_decision.",
        }
    return {
        "tested_decision": decision,
        "disposition": "approved",
        "semantic_independence": "INDEPENDENT_OR_PRIMARY",
        "related_to": "",
        "repair_required": False,
        "repair_summary": "",
    }


def validate_overlay(predecessor_ids: list[str]) -> list[str]:
    errors: list[str] = []
    if set(predecessor_ids) != set(DECISIONS):
        missing = sorted(set(predecessor_ids) - set(DECISIONS))
        extra = sorted(set(DECISIONS) - set(predecessor_ids))
        if missing:
            errors.append(f"overlay missing predecessors: {missing[:10]}")
        if extra:
            errors.append(f"overlay extra ids: {extra[:10]}")
    for qid, related in WITHHELD.items():
        if qid not in DECISIONS:
            errors.append(f"withheld id not in decisions: {qid}")
        if related not in DECISIONS:
            errors.append(f"withhold related id missing: {related}")
        if related in WITHHELD:
            errors.append(f"withhold target is itself withheld: {related}")
        if DECISIONS.get(qid) != DECISIONS.get(related):
            errors.append(f"withheld {qid} decision differs from {related}")
    return errors


def as_mapping() -> Mapping[str, Mapping[str, Any]]:
    return {qid: overlay_row(qid) for qid in DECISIONS}
